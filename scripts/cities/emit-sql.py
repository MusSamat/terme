#!/usr/bin/env python3
"""Emit the settlements directory (prisma/seed-data/cities.json) as SQL.

Writes an idempotent upsert keyed on soate_code (is_active only on insert —
an admin's enable / disable survives a rebuild) into the table named by the
first argument (default "cities"), then resolves parent / oblast / raion links
from the SOATE codes. Paste the output into a Prisma migration whenever the
directory is rebuilt:

  python3 scripts/cities/emit-sql.py cities >> prisma/migrations/<new>/migration.sql
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PRIORITY = {'capital': 100, 'airport': 90, 'city': 80, 'town': 50, 'village': 10}


def q(v):
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def arr(xs):
    return "ARRAY[" + ",".join(q(x) for x in xs) + "]::text[]" if xs else "'{}'::text[]"


def osm(osm_id):
    if not osm_id:
        return 'NULL', 'NULL'
    kind = {'n': 'node', 'w': 'way', 'r': 'relation'}[osm_id[0]]
    return q(kind), osm_id[1:]


def main():
    table = sys.argv[1] if len(sys.argv) > 1 else 'cities'
    rows = json.loads((ROOT / 'prisma' / 'seed-data' / 'cities.json').read_text(encoding='utf-8'))
    out = [f'-- {len(rows)} rows generated by scripts/cities/emit-sql.py from prisma/seed-data/cities.json',
           f'INSERT INTO "{table}" (soate_code, parent_soate, type, name_ru, name_kg, aliases, lat, lng,',
           '  coord_approx, osm_type, osm_id, priority, is_searchable, is_active) VALUES']
    values = []
    for r in rows:
        osm_type, osm_id = osm(r['osm_id'])
        values.append('  (' + ', '.join([
            q(r['code']), q(r['parent']), q(r['type']), q(r['name_ru']), q(r['name_kg']),
            arr(r['aliases']), q(r['lat']), q(r['lng']), q(r['approx']), osm_type, osm_id,
            str(PRIORITY.get(r['type'], 0)), q(r['searchable']), q(r.get('active', True)),
        ]) + ')')
    out.append(',\n'.join(values))
    out.append("""ON CONFLICT (soate_code) DO UPDATE SET
  parent_soate = EXCLUDED.parent_soate, type = EXCLUDED.type,
  name_ru = EXCLUDED.name_ru, name_kg = EXCLUDED.name_kg, aliases = EXCLUDED.aliases,
  lat = EXCLUDED.lat, lng = EXCLUDED.lng, coord_approx = EXCLUDED.coord_approx,
  osm_type = EXCLUDED.osm_type, osm_id = EXCLUDED.osm_id,
  priority = EXCLUDED.priority, is_searchable = EXCLUDED.is_searchable;
""")
    out.append(f"""UPDATE "{table}" c SET parent_id = p.id
  FROM "{table}" p WHERE p.soate_code = c.parent_soate AND c.parent_id IS DISTINCT FROM p.id;
UPDATE "{table}" c SET
  oblast_id = (SELECT o.id FROM "{table}" o
               WHERE o.soate_code = '417' || substr(c.soate_code, 4, 2) || '000000000'
                 AND o.id <> c.id),
  raion_id = (SELECT r.id FROM "{table}" r
              WHERE r.soate_code = '417' || substr(c.soate_code, 4, 5) || '000000'
                AND r.type IN ('raion', 'city_district') AND r.id <> c.id)
  WHERE c.soate_code LIKE '417%';
-- Non-SOATE rows (osm:* villages, airport:*) hang off a raion or an oblast.
UPDATE "{table}" c SET
  raion_id = CASE WHEN p.type = 'raion' THEN p.id END,
  oblast_id = CASE WHEN p.type = 'oblast' THEN p.id ELSE p.oblast_id END
  FROM "{table}" p WHERE c.soate_code NOT LIKE '417%' AND p.id = c.parent_id;
""")
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
